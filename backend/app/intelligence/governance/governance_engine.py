class GovernanceEngine:
    """Enterprise governance, observability, and audit coordinator."""

    def __init__(self):
        self.store = get_audit_store()

    def evaluate_and_record(
        self,
        category: PolicyCategory,
        operation: str,
        actor_type: ActorType = ActorType.SYSTEM,
        actor_id: str = "system",
        user_id: str = "default_user",
        database_identity: str = "none",
        agent_id: Optional[str] = None,
        context: Optional[Dict[str, Any]] = None,
        operation_type: str = "READ_ONLY",
        affected_rows: int = 0,
        agent_permission: Optional[str] = None,
    ) -> Tuple[PolicyDecision, RiskAssessment, GovernanceAuditEvent]:
        """
        Evaluates operation against active policies, calculates deterministic risk,
        and records a tamper-evident audit log event.
        """
        if agent_permission is None:
            if actor_id == "action_agent" or agent_id == "action_agent":
                agent_permission = "FULL_ACTION"
            else:
                agent_permission = "READ_ONLY"

        ctx = dict(context or {})
        if operation_type == "MUTATION":
            ctx["is_mutation"] = True
        ctx["agent_permission"] = agent_permission

        # 1. Policy evaluation
        decision, applied_policies, rationale = PolicyEngine.evaluate(
            category=category,
            operation=operation,
            context=ctx,
            user_id=user_id,
        )

        # 2. Risk assessment
        risk = GovernanceRiskEngine.assess_risk(
            operation=operation,
            operation_type=operation_type,
            affected_rows=affected_rows,
            agent_permission=agent_permission,
            context=ctx,
        )

        # Map decision to event type
        now_iso = datetime.now(timezone.utc).isoformat()
        if decision == PolicyDecision.DENY:
            event_type = GovernanceEventType.POLICY_BLOCK
            result_str = "DENIED"
        elif decision == PolicyDecision.REQUIRE_CONFIRMATION:
            event_type = GovernanceEventType.ACTION_PROPOSED
            result_str = "AWAITING_CONFIRMATION"
        else:
            event_type = GovernanceEventType.POLICY_CHECK
            result_str = "ALLOWED"

        # 3. Log audit event
        audit_event = GovernanceAuditEvent(
            event_id="",  # Auto-generated by store
            timestamp=now_iso,
            user_id=user_id,
            database_identity=database_identity,
            event_type=event_type,
            resource_type="OPERATION",
            resource_id=operation[:50],
            actor_type=actor_type,
            action=operation,
            result=result_str,
            risk_level=risk.risk_level,
            policy_result=decision,
            agent_id=agent_id,
            metadata={
                "rationale": rationale,
                "applied_policies": applied_policies,
                "risk_factors": risk.contributing_factors,
                "required_control": risk.required_control,
            },
        )
        saved_event = self.store.save_audit_event(audit_event)

        return decision, risk, saved_event

    def log_audit_event(self, event: GovernanceAuditEvent) -> GovernanceAuditEvent:
        """Persist an audit event into the cryptographic hash chain."""
        return self.store.save_audit_event(event)

    def log_security_event(
        self,
        event_type: SecurityEventType,
        user_id: str,
        database_identity: str,
        summary: str,
        severity: SecurityEventSeverity = SecurityEventSeverity.MEDIUM,
        actor_id: str = "anonymous",
        agent_id: Optional[str] = None,
        details: Optional[Dict[str, Any]] = None,
    ) -> SecurityEventRecord:
        """Log a security event and cross-link it in the audit chain."""
        return SecurityEventManager.log_security_event(
            user_id=user_id,
            database_identity=database_identity,
            event_type=event_type,
            severity=severity,
            source="governance_engine",
            resource="API",
            description=summary,
            metadata=details,
        )

    def track_data_access(
        self,
        user_id: str,
        database_identity: str,
        raw_sql: str,
        operation: str = "SELECT",
        agent_id: Optional[str] = None,
        duration_ms: float = 0.0,
        row_count: Optional[int] = None,
        status: str = "SUCCESS",
    ) -> DataAccessEvent:
        """Track a data access query with parameter redaction."""
        return DataAccessTracker.log_access(
            user_id=user_id,
            database_identity=database_identity,
            query_text=raw_sql,
            operation=operation,
            agent_id=agent_id,
            duration_ms=duration_ms,
            row_count=row_count,
            status=status,
        )

    def start_agent_trace(
        self,
        request_id: str,
        agent_id: str,
        user_id: str,
        database_identity: str,
        tool_or_capability: str,
        orchestration_id: Optional[str] = None,
        step_id: Optional[str] = None,
    ) -> AgentTraceRecord:
        """Begin telemetry tracing for an agent step."""
        return AgentTraceStore.start_trace(
            user_id=user_id,
            database_identity=database_identity,
            agent_id=agent_id,
            tool_or_capability=tool_or_capability,
            request_id=request_id,
            orchestration_id=orchestration_id,
            step_id=step_id,
        )

    def complete_agent_trace(
        self,
        trace_id: str,
        user_id: str = "default_user",
        status: str = "SUCCESS",
        duration_ms: float = 0.0,
        evidence_count: int = 0,
        error_message: Optional[str] = None,
    ) -> Optional[AgentTraceRecord]:
        """Conclude telemetry tracing and log completion to audit chain."""
        return AgentTraceStore.complete_trace(
            trace_id=trace_id,
            user_id=user_id,
            status=status,
            duration_ms=duration_ms,
            evidence_count=evidence_count,
            error_message=error_message,
        )

    def get_summary(
        self,
        user_id: str,
        database_identity: str,
        time_window: str = "24h",
    ) -> GovernanceSummary:
        """Fetch unified governance summary metrics."""
        return get_governance_summary(
            user_id=user_id,
            database_identity=database_identity,
            time_window=time_window,
        )

    def get_agent_metrics(
        self,
        user_id: str,
        database_identity: str,
    ) -> List[AgentObservabilityMetric]:
        """Fetch observability telemetry metrics per agent."""
        return get_agent_observability_metrics(
            user_id=user_id,
            database_identity=database_identity,
        )

    def generate_report(
        self,
        user_id: str,
        database_identity: str,
        period_hours: int = 24,
    ) -> ComplianceReport:
        """Generate compliance report separating facts and interpretations."""
        return generate_compliance_report(
            user_id=user_id,
            database_identity=database_identity,
            period_hours=period_hours,
        )

    def verify_audit_chain(self, user_id: Optional[str] = None) -> Tuple[bool, int, List[str]]:
        """Verify cryptographic integrity of audit chain."""
        return self.store.verify_audit_chain(user_id=user_id or "default_user")


_engine_instance: Optional[GovernanceEngine] = None


def get_governance_engine() -> GovernanceEngine:
    """Return singleton GovernanceEngine instance."""
    global _engine_instance
    if _engine_instance is None:
        _engine_instance = GovernanceEngine()
    return _engine_instance
